            '</script>\n'
            '<script>\n'
            '// Nearest cinema highlight - reorder showtime rows\n'
            '(function(){\n'
            'var coords={'
            + ",".join(f'"{s}":{{lat:{lat},lng:{lng}}}' for s, lat, lng in [("st-austell",50.338,-4.795),("newquay",50.414,-5.075),("wadebridge",50.517,-4.835),("truro",50.263,-5.051)])
